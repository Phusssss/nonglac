// Hàm tính khoảng cách giữa 2 điểm GPS (km)
export const calculateDistance = (lat1, lng1, lat2, lng2) => {
  const R = 6371; // Bán kính Trái Đất (km)
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLng = (lng2 - lng1) * Math.PI / 180;
  const a = 
    Math.sin(dLat/2) * Math.sin(dLat/2) +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) * 
    Math.sin(dLng/2) * Math.sin(dLng/2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1-a));
  return R * c;
};

// Hàm tìm tỉnh gần nhất với vị trí hiện tại
export const findNearestProvince = (currentLat, currentLng) => {
  let nearestProvince = null;
  let minDistance = Infinity;

  vietnamProvinces.forEach(province => {
    const distance = calculateDistance(currentLat, currentLng, province.lat, province.lng);
    if (distance < minDistance) {
      minDistance = distance;
      nearestProvince = { ...province, distance };
    }
  });

  return nearestProvince;
};

// Hàm kiểm tra vị trí có khớp với tỉnh đã chọn không
export const verifyLocation = (selectedProvince, currentLat, currentLng, maxDistance = 100) => {
  // Tìm tỉnh bằng cách so sánh chính xác hoặc gần đúng
  let province = vietnamProvinces.find(p => p.name === selectedProvince);
  
  // Nếu không tìm thấy chính xác, thử tìm kiếm gần đúng
  if (!province) {
    province = vietnamProvinces.find(p => 
      p.name.toLowerCase().includes(selectedProvince.toLowerCase()) ||
      selectedProvince.toLowerCase().includes(p.name.toLowerCase())
    );
  }
  
  if (!province) {
    console.log('Không tìm thấy tỉnh:', selectedProvince);
    console.log('Danh sách tỉnh có sẵn:', vietnamProvinces.map(p => p.name));
    return { 
      isValid: false, 
      message: `Tỉnh "${selectedProvince}" không hợp lệ hoặc không tìm thấy trong hệ thống` 
    };
  }

  const distance = calculateDistance(currentLat, currentLng, province.lat, province.lng);
  
  return {
    isValid: distance <= maxDistance,
    distance: Math.round(distance),
    message: distance <= maxDistance 
      ? `Vị trí xác thực thành công (cách ${Math.round(distance)}km)`
      : `Vị trí không khớp. Bạn đang cách ${province.name} khoảng ${Math.round(distance)}km`
  };
};